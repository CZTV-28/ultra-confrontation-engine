interface SeasonRosterPageProps {
  goBack: () => void;
  navigateTo: (page: "review") => void;
}

type Language = "zh" | "en";
type SeasonRosterId = "S1" | "S2" | "S3" | "S4";

const OFFICIAL_REVISION_REQUEST_KEY = "uce:review:official-revision-character-id";

interface RosterDraft {
  characterId: string;
  characterName: string;
  projectName: string;
  creator: string;
  reviewDecision: S1ReviewDecision;
  officialNotes: string;
}

const seasonModules: Array<{ id: SeasonRosterId; name: string; capacity: number; enabled: boolean }> = [
  { id: "S1", name: "起源", capacity: S1_ROSTER_SIZE, enabled: true },
  { id: "S2", name: "未定", capacity: S1_ROSTER_SIZE, enabled: false },
  { id: "S3", name: "未定", capacity: S1_ROSTER_SIZE, enabled: false },
  { id: "S4", name: "未定", capacity: S1_ROSTER_SIZE, enabled: false },
];

const emptyDraft: RosterDraft = {
  characterId: "",
  characterName: "",
  projectName: "",
  creator: "",
  reviewDecision: "pending",
  officialNotes: "",
};

