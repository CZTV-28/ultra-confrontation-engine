import { useTranslation } from "react-i18next";
import UCWindow from "../../components/common/UCWindow/UCWindow";
import {
  S1_ROSTER_SIZE,
  getS1RosterStats,
  loadS1Roster,
  removeS1RosterEntry,
  readS1Roster,
  saveS1RosterEntry,
  type S1ReviewDecision,
  type S1RosterSlot,
} from "../../services/s1Roster";
